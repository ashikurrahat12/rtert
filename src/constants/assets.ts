import type { AssetDefinition } from '../types/trading.ts';

function otcPair(
  symbol: string,
  name: string,
  payout: number,
  decimals: number
): AssetDefinition {
  const cleanPair = symbol.replace(' (OTC)', '');
  const [baseCurrency, quoteCurrency] = cleanPair.split('/');
  return {
    symbol,
    name,
    category: 'otc',
    payout,
    decimals,
    baseCurrency,
    quoteCurrency,
    source: 'otc',
    providerSymbol: `${baseCurrency}${quoteCurrency}`,
    marketHours: '24/7',
  };
}

